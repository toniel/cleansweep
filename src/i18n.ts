const dicts: Record<string, Record<MessageKey, string>> = { id, en };

export const i18nState = reactive({ locale: "id" as "id" | "en" });

export function t(key: MessageKey, params?: Record<string, string>): string {
  let s: string = dicts[i18nState.locale]?.[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, v);
  }
  return s;
}
